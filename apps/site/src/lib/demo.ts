import type { Hit, SourceLine } from "@ixos/ui";
export interface DemoFile {
  path: string;
  /** Keyword half of the hybrid score. */
  keyword: number;
  /** Meaning half of the hybrid score. */
  meaning: number;
}

export interface RankedFile extends DemoFile {
  /** The matched passage. */
  start: number;
  end: number;
  /** The file around it, starting at line `from`. */
  from: number;
  text: string[];
}

export interface Demo {
  query: string;
  keywords: DemoFile[];
  ranked: RankedFile[];
}

