export function toHit(file: DemoFile | RankedFile): Hit {
  const slash = file.path.lastIndexOf("/");
  return {
    key: file.path,
    file: file.path.slice(slash + 1),
    dir: file.path.slice(0, slash),
    lines: "start" in file ? `${file.start}–${file.end}` : undefined,
    keyword: file.keyword,
    meaning: file.meaning,
  };
}

export function sourceLines(file: RankedFile): SourceLine[] {
  return file.text.map((text, index) => ({ n: file.from + index, text }));
}
