import {
  FileText,
  FileCode,
  FileSpreadsheet,
  Image,
  Mail,
  Presentation,
  File,
  Database,
  Settings,
  FileJson,
  type LucideIcon,
} from 'lucide-react';

const ICON_MAP: Record<string, LucideIcon> = {
  pdf: FileText,
  doc: FileText,
  docx: FileText,
  txt: FileText,
  md: FileCode,
  ts: FileCode,
  tsx: FileCode,
  js: FileCode,
  py: FileCode,
  rs: FileCode,
  sql: Database,
  json: FileJson,
  yml: Settings,
  yaml: Settings,
  toml: Settings,
  env: Settings,
  conf: Settings,
  nginx: Settings,
  xlsx: FileSpreadsheet,
  xls: FileSpreadsheet,
  csv: FileSpreadsheet,
  jpg: Image,
  jpeg: Image,
  png: Image,
  gif: Image,
  webp: Image,
  svg: Image,
  eml: Mail,
  msg: Mail,
  pptx: Presentation,
  ppt: Presentation,
  dockerfile: Settings,
};

export function getFileIcon(extension: string): LucideIcon {
  return ICON_MAP[extension.toLowerCase()] ?? File;
}
